/* mp_menu_sites.c: the frontend patterns.
 *
 * All twelve are masked from the DISASSEMBLY rather than by a byte heuristic: every relative branch
 * displacement and every operand that is an address inside the image is masked, and everything
 * else is required. That is why they hold across all six checked builds including the Edit Tool's
 * recompile, whose addresses move by up to 0x60.
 *
 * Two of them are longer than the rest and the reason is worth stating. `swmenu_close` and
 * `swmenu_getWidgetState` both begin with the same shape as several of their neighbours, a frame
 * setup and a call through a masked displacement, so twenty bytes of them match three and four
 * places respectively. Thirty two bytes reach past the shared shape into what each one actually
 * does, and then both are unique everywhere.
 *
 * `title_main_menu` is longer again, seventy three bytes, and that is not for uniqueness: it is
 * unique at twenty. It reaches to the call to `swmenu_build` because FOUR addresses fall out of
 * the pushes in front of it, and the cell table requires an operand to lie inside the pattern that
 * proves it. One site, four cells: the screen's widget array, its bitmap name table, the shared
 * font name table, and the screen slot that says whether the title menu is the one on screen.
 */
