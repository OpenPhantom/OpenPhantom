static bool   resolved_once;
static size_t resolved_count;

size_t mp_signatures_voice_resolve(void)
{
    if (resolved_once) {
        return resolved_count;
    }
    resolved_once  = true;
    resolved_count = signature_resolve_table(voice_sites, MP_VOICE_SITE_COUNT);
    log_info("%u of %u voice site(s) resolved", (unsigned)resolved_count,
             (unsigned)MP_VOICE_SITE_COUNT);
    return resolved_count;
}

uintptr_t mp_signatures_voice_address(mp_voice_site_t site)
{
    return ((size_t)site < (size_t)MP_VOICE_SITE_COUNT) ? voice_sites[site].address : 0u;
}

size_t mp_signatures_voice_prologue(mp_voice_site_t site)
{
    return ((size_t)site < (size_t)MP_VOICE_SITE_COUNT) ? voice_sites[site].detour_prologue : 0u;
}

const signature_t *mp_signatures_voice_site(mp_voice_site_t site)
{
    return ((size_t)site < (size_t)MP_VOICE_SITE_COUNT) ? &voice_sites[site] : NULL;
}
